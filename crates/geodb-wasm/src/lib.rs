fn format_results_array(array: &JsValue) -> String {
    let arr = js_sys::Array::from(array);
    let mut html = String::new();
    for i in 0..arr.length() {
        html.push_str(&format_result_jsvalue(&arr.get(i)));
    }
    html
}

