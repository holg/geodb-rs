static LAST_HASH: OnceLock<std::sync::Mutex<String>> = OnceLock::new();

fn get_last_hash() -> String {
    LAST_HASH
        .get_or_init(|| std::sync::Mutex::new(String::new()))
        .lock()
        .unwrap()
        .clone()
}

fn set_last_hash(h: &str) {
    let mut lock = LAST_HASH
        .get_or_init(|| std::sync::Mutex::new(String::new()))
        .lock()
        .unwrap();
    *lock = h.to_string();
}

#[wasm_bindgen]
#[derive(Debug, Clone)]
pub struct WasmResult {
    #[wasm_bindgen(skip)]
    pub kind: String,
    #[wasm_bindgen(skip)]
    pub name: String,
    #[wasm_bindgen(skip)]
    pub country: String,
    #[wasm_bindgen(skip)]
    pub state: String,
    #[wasm_bindgen(skip)]
    pub iso2: String,
    #[wasm_bindgen(skip)]
    pub iso3: String,
    #[wasm_bindgen(skip)]
    pub phone: String,
    #[wasm_bindgen(skip)]
    pub capital: String,
    #[wasm_bindgen(skip)]
    pub region: String,
    #[wasm_bindgen(skip)]
    pub emoji: String,
    pub lat: f64,
    pub lng: f64,
    pub pop: u32,
    pub score: i32,
}

#[wasm_bindgen]
impl WasmResult {
    #[wasm_bindgen(getter)]
    pub fn kind(&self) -> String {
        self.kind.clone()
    }
    #[wasm_bindgen(getter)]
    pub fn name(&self) -> String {
        self.name.clone()
    }
    #[wasm_bindgen(getter)]
    pub fn country(&self) -> String {
        self.country.clone()
    }
    #[wasm_bindgen(getter)]
    pub fn state(&self) -> String {
        self.state.clone()
    }
    #[wasm_bindgen(getter)]
    pub fn iso2(&self) -> String {
        self.iso2.clone()
    }
    #[wasm_bindgen(getter)]
    pub fn iso3(&self) -> String {
        self.iso3.clone()
    }
    #[wasm_bindgen(getter)]
    pub fn phone(&self) -> String {
        self.phone.clone()
    }
    #[wasm_bindgen(getter)]
    pub fn capital(&self) -> String {
        self.capital.clone()
    }
    #[wasm_bindgen(getter)]
    pub fn region(&self) -> String {
        self.region.clone()
    }
    #[wasm_bindgen(getter)]
    pub fn emoji(&self) -> String {
        self.emoji.clone()
    }

    pub fn to_sexpr(&self) -> String {
        format!(
            "({} :name {:?} :country {:?} :state {:?} :iso2 {:?} :iso3 {:?} :phone {:?} :capital {:?} :region {:?} :emoji {:?} :lat {:.4} :lng {:.4} :pop {} :score {})",
            self.kind, self.name, self.country, self.state, self.iso2, self.iso3, self.phone, self.capital, self.region, self.emoji, self.lat, self.lng, self.pop, self.score
        )
    }

    pub fn to_json(&self) -> String {
        serde_json::to_string(&serde_json::json!({
            "kind": self.kind,
            "name": self.name,
            "country": self.country,
            "state": self.state,
            "iso2": self.iso2,
            "iso3": self.iso3,
            "phone": self.phone,
            "capital": self.capital,
            "region": self.region,
            "emoji": self.emoji,
            "latitude": self.lat,
            "longitude": self.lng,
            "population": self.pop,
            "score": self.score,
        }))
        .unwrap_or_default()
    }
}

#[cfg(target_arch = "wasm32")]
#[wasm_bindgen(start)]
pub fn start() {
    console_error_panic_hook::set_once();
    web_sys::console::log_1(&"Initializing GeoDB WASM module...".into());

    DB.get_or_init(|| {
        // ... decompression logic ...
        let mut decoder = GzDecoder::new(EMBEDDED_DB);
        let mut decompressed = Vec::new();
        decoder
            .read_to_end(&mut decompressed)
            .expect("Decompression failed");

        // ... deserialization ...
        let db: DefaultGeoDb = bincode::deserialize(&decompressed).expect("Deserialize failed");

        // Update stats box in UI from Rust (only if window exists - not in Node.js tests)
        if let Some(window) = web_sys::window() {
            if let Some(document) = window.document() {
                if let Some(stats_el) = document.get_element_by_id("stats") {
                    let stats = db.stats();
                    stats_el.set_inner_html(&format!(
                        "<strong>Database Statistics (Rust)</strong><br>\
                         Countries: {}<br>\
                         States/Regions: {}<br>\
                         Cities: {}",
                        stats.countries, stats.states, stats.cities
                    ));
                }
            }
        }

        db
    });

    // Automatically trigger run_app on start when using Trunk (only if window exists)
    // In Node.js tests, window() returns None, so we skip UI setup
    if web_sys::window().is_some() {
        run_app();
    }
}

